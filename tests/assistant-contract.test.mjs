import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { test } from 'node:test'

const root = new URL('../', import.meta.url)
const read = (path) => readFile(new URL(path, root), 'utf8')

test('assistant API enforces authenticated access and bounded provider work', async () => {
  const route = await read('app/api/assistant/route.ts')
  assert.match(route, /supabase\.auth\.getUser\(\)/)
  assert.match(route, /code: 'unauthorized'/)
  assert.match(route, /retryOptions: \{ attempts: 1 \}/)
  assert.match(route, /export const maxDuration = 15/)
  assert.match(route, /MAX_MESSAGES = 20/)
  assert.match(route, /MAX_MESSAGE_LENGTH = 2000/)
})

test('demo planning output is visibly separated from live AI output', async () => {
  const page = await read('app/page.tsx')
  assert.match(page, /Sample plan — Demo Mode, not generated by live Gemini/)
  assert.match(page, /Use Demo Planning Mode/)
  assert.match(page, /mode === 'demo'/)
  assert.match(page, /mode: 'live'/)
})

test('server proxy protects every workspace route', async () => {
  const proxy = await read('lib/supabase/proxy.ts')
  assert.match(proxy, /const protectedPaths = \[/)
  for (const route of ['/', '/events', '/timeline', '/budget', '/guests', '/vendors', '/ai-ideas']) {
    assert.equal(proxy.includes(`'${route}'`), true, `missing protected route ${route}`)
  }
  assert.match(proxy, /url\.pathname = '\/auth\/login'/)
})
